/* V153 DEV additions. Kept here because this file already loads before app.js. */
(() => {
  'use strict';

  const scope = (() => {
    const first = decodeURIComponent(location.pathname.split('/').filter(Boolean)[0] || 'root');
    return first.toLowerCase().replace(/[^a-z0-9_-]+/g,'-') || 'root';
  })();
  const renameKey = `galaxy_sprite_tracker_name_overrides_v153_${scope}`;
  const progressKey = `galaxy_sprite_tracker_progress_v2_${scope}`;
  const css = document.createElement('link');
  css.rel = 'stylesheet';
  css.href = 'v153.css?v=153';
  document.head.appendChild(css);

  const readJson = (key,fallback = {}) => {
    try { return JSON.parse(localStorage.getItem(key) || 'null') || fallback; }
    catch { return fallback; }
  };
  const writeJson = (key,value) => localStorage.setItem(key,JSON.stringify(value));
  const renames = readJson(renameKey,{ families:{} });
  renames.families ||= {};

  function applyRenameOverridesToPublishedDesign(design) {
    if (!design || typeof design !== 'object') return design;
    design.families ||= {};
    Object.entries(renames.families || {}).forEach(([familyId,entry]) => {
      if (!entry || typeof entry !== 'object') return;
      const family = design.families[familyId] ||= {};
      if (entry.name) family.name = String(entry.name).slice(0,80);
      family.variants ||= {};
      Object.entries(entry.variants || {}).forEach(([variantId,name]) => {
        if (!name) return;
        const variant = family.variants[variantId] ||= {};
        variant.name = String(name).slice(0,80);
      });
    });
    return design;
  }

  /* Apply saved DEV names before app.js creates its private design copy. */
  if (window.PUBLISHED_DESIGN) applyRenameOverridesToPublishedDesign(window.PUBLISHED_DESIGN);

  /* Also feed rename overrides into the existing Admin publisher when it reads
     published-design.js from GitHub. No service-role or secret is added here. */
  const nativeFetch = window.fetch.bind(window);
  window.fetch = async (...args) => {
    const request = args[0];
    const url = typeof request === 'string' ? request : request?.url || '';
    const response = await nativeFetch(...args);
    if (!/api\.github\.com\/repos\/SnorkyTheBeard\/Sprite-Checklist-Dev\/contents\/published-design\.js/i.test(url) || !response.ok) return response;
    try {
      const payload = await response.clone().json();
      if (!payload?.content) return response;
      const binary = atob(String(payload.content).replace(/\s/g,''));
      const bytes = Uint8Array.from(binary,(c) => c.charCodeAt(0));
      const source = new TextDecoder().decode(bytes);
      const equals = source.indexOf('=');
      const semicolon = source.lastIndexOf(';');
      if (equals < 0 || semicolon <= equals) return response;
      const design = JSON.parse(source.slice(equals + 1,semicolon).trim());
      applyRenameOverridesToPublishedDesign(design);
      const nextSource = `// Generated by Sprite Checklist. Artwork is stored in published-assets.\nwindow.PUBLISHED_DESIGN = ${JSON.stringify(design)};\n`;
      const encoded = btoa(unescape(encodeURIComponent(nextSource)));
      const nextPayload = { ...payload,content:encoded };
      return new Response(JSON.stringify(nextPayload),{
        status:response.status,
        statusText:response.statusText,
        headers:new Headers(response.headers)
      });
    } catch {
      return response;
    }
  };

  const clean = (value) => String(value || '').trim().replace(/\s+/g,' ').slice(0,80);
  const catalog = () => {
    const base = Array.isArray(window.SPRITE_DATA) ? window.SPRITE_DATA : [];
    const design = window.PUBLISHED_DESIGN || {};
    const custom = Array.isArray(design.customFamilies) ? design.customFamilies : [];
    const families = new Map();
    [...base,...custom].forEach((family) => {
      if (family?.id && !families.has(family.id)) families.set(family.id,family);
    });
    return [...families.values()].flatMap((family) => {
      const familyDesign = design.families?.[family.id] || {};
      const familyName = familyDesign.name || family.name || 'Sprite';
      const rarity = familyDesign.rarity || family.rarity || 'Rare';
      const variants = new Map();
      [...(Array.isArray(family.variants) ? family.variants : []),
       ...(Array.isArray(familyDesign.addedVariants) ? familyDesign.addedVariants : [])]
        .forEach((variant) => { if (variant?.id && !variants.has(variant.id)) variants.set(variant.id,variant); });
      return [...variants.values()].flatMap((variant) => {
        const view = familyDesign.variants?.[variant.id] || {};
        if (view.deleted || view.visible === false) return [];
        return [{
          familyId:family.id,
          variantId:variant.id,
          familyName,
          variantName:view.name || variant.name || 'Variant',
          rarity,
          image:view.image || variant.image || ''
        }];
      });
    });
  };

  function ensureRenameDialog() {
    if (document.getElementById('v153RenameDialog')) return;
    const dialog = document.createElement('dialog');
    dialog.id = 'v153RenameDialog';
    dialog.className = 'v153-dialog';
    dialog.innerHTML = `
      <form method="dialog" id="v153RenameForm">
        <h2>Edit Sprite Name</h2>
        <input type="hidden" id="v153RenameFamilyId">
        <input type="hidden" id="v153RenameVariantId">
        <label>Sprite group name<input id="v153RenameFamilyName" maxlength="80" autocomplete="off"></label>
        <label>Variant name<input id="v153RenameVariantName" maxlength="80" autocomplete="off"></label>
        <p class="v153-import-status">The internal Sprite IDs stay unchanged, so saved collection progress remains attached.</p>
        <div class="v153-dialog-actions">
          <button type="button" id="v153RenameCancel">Cancel</button>
          <button type="submit" class="primary">Save Name</button>
        </div>
      </form>`;
    document.body.appendChild(dialog);
    dialog.querySelector('#v153RenameCancel').addEventListener('click',() => dialog.close());
    dialog.querySelector('#v153RenameForm').addEventListener('submit',(event) => {
      event.preventDefault();
      const familyId = dialog.querySelector('#v153RenameFamilyId').value;
      const variantId = dialog.querySelector('#v153RenameVariantId').value;
      const familyName = clean(dialog.querySelector('#v153RenameFamilyName').value);
      const variantName = clean(dialog.querySelector('#v153RenameVariantName').value);
      if (!familyId || !variantId || !familyName || !variantName) return;
      renames.families[familyId] ||= { variants:{} };
      renames.families[familyId].variants ||= {};
      renames.families[familyId].name = familyName;
      renames.families[familyId].variants[variantId] = variantName;
      writeJson(renameKey,renames);
      dialog.close();
      location.reload();
    });
  }

  function addRenameButtons() {
    if (!document.body.classList.contains('sprite-edit-mode')) return;
    const entries = catalog();
    document.querySelectorAll('.card[data-family-id][data-variant-id]').forEach((card) => {
      if (card.querySelector('.v153-name-edit-btn')) return;
      const familyId = card.dataset.familyId;
      const variantId = card.dataset.variantId;
      const info = entries.find((entry) => entry.familyId === familyId && entry.variantId === variantId);
      if (!info) return;
      const tools = card.querySelector('.sprite-card-tools');
      if (!tools) return;
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'v153-name-edit-btn';
      button.textContent = 'Name';
      button.setAttribute('aria-label',`Edit name for ${info.familyName} ${info.variantName}`);
      button.addEventListener('click',() => {
        ensureRenameDialog();
        const dialog = document.getElementById('v153RenameDialog');
        dialog.querySelector('#v153RenameFamilyId').value = familyId;
        dialog.querySelector('#v153RenameVariantId').value = variantId;
        dialog.querySelector('#v153RenameFamilyName').value = info.familyName;
        dialog.querySelector('#v153RenameVariantName').value = info.variantName;
        dialog.showModal();
        requestAnimationFrame(() => dialog.querySelector('#v153RenameVariantName').focus({ preventScroll:true }));
      });
      tools.appendChild(button);
    });
  }

  function addPerFamilyCollapseButtons() {
    document.querySelectorAll('.collection[data-family-id]').forEach((section) => {
      if (section.querySelector(':scope > .v153-family-collapse-wrap')) return;
      if (!section.querySelector('.card')) return;
      const wrap = document.createElement('div');
      wrap.className = 'v153-family-collapse-wrap';
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'v153-family-collapse';
      button.textContent = 'Collapse Variants';
      button.addEventListener('click',() => {
        const collapsed = section.classList.toggle('v153-family-collapsed');
        button.textContent = collapsed ? 'Show Variants' : 'Collapse Variants';
        button.setAttribute('aria-expanded',String(!collapsed));
        if (collapsed) section.scrollIntoView({ block:'nearest',behavior:'smooth' });
      });
      button.setAttribute('aria-expanded','true');
      wrap.appendChild(button);
      section.appendChild(wrap);
    });
  }

  function importCatalogLabel(entry) {
    return `${entry.familyName} — ${entry.variantName} (${entry.rarity})`;
  }

  function ensureImporter() {
    if (document.getElementById('v153ImportDialog')) return;
    const dialog = document.createElement('dialog');
    dialog.id = 'v153ImportDialog';
    dialog.className = 'v153-dialog v153-import-dialog';
    dialog.innerHTML = `
      <form id="v153ImportForm">
        <div class="v153-import-top">
          <h2>Import Sprites</h2>
          <label>Screenshot with up to 6 Sprites
            <input id="v153ImportFile" type="file" accept="image/*" capture="environment">
          </label>
          <div class="v153-import-preview" id="v153ImportPreview" hidden><img alt="Screenshot preview"></div>
          <p class="v153-import-status" id="v153ImportStatus">Choose a screenshot. Detection will suggest up to six matches, and you review everything before anything is added.</p>
        </div>
        <div class="v153-import-review" id="v153ImportReview"></div>
        <div></div>
        <div class="v153-dialog-actions">
          <button type="button" id="v153ImportCancel">Cancel</button>
          <button type="button" id="v153ImportAnalyze">Analyze Screenshot</button>
          <button type="submit" class="primary" id="v153ImportConfirm" disabled>Add to Collection</button>
        </div>
      </form>`;
    document.body.appendChild(dialog);
    const file = dialog.querySelector('#v153ImportFile');
    const preview = dialog.querySelector('#v153ImportPreview');
    const status = dialog.querySelector('#v153ImportStatus');
    const analyze = dialog.querySelector('#v153ImportAnalyze');
    const confirm = dialog.querySelector('#v153ImportConfirm');
    const review = dialog.querySelector('#v153ImportReview');
    let imageData = '';

    const makeRows = (matches = []) => {
      const entries = catalog();
      review.replaceChildren();
      const count = Math.min(6,Math.max(matches.length,1));
      for (let index = 0; index < count; index += 1) {
        const match = matches[index] || {};
        const row = document.createElement('article');
        row.className = 'v153-import-row';
        const copy = document.createElement('div');
        copy.className = 'v153-import-row-copy';
        const select = document.createElement('select');
        select.dataset.importIndex = String(index);
        const blank = document.createElement('option');
        blank.value = '';
        blank.textContent = `Sprite ${index + 1} — choose match`;
        select.appendChild(blank);
        entries.forEach((entry) => {
          const option = document.createElement('option');
          option.value = `${entry.familyId}::${entry.variantId}`;
          option.textContent = importCatalogLabel(entry);
          if (entry.familyId === match.familyId && entry.variantId === match.variantId) option.selected = true;
          select.appendChild(option);
        });
        const confidence = document.createElement('span');
        confidence.className = 'v153-import-confidence';
        confidence.textContent = Number.isFinite(Number(match.confidence))
          ? `${Math.round(Number(match.confidence) * 100)}% suggested match`
          : 'Review or correct this match';
        copy.append(select,confidence);
        const masteredLabel = document.createElement('label');
        const mastered = document.createElement('input');
        mastered.type = 'checkbox';
        mastered.dataset.masteredIndex = String(index);
        mastered.checked = match.mastered === true;
        masteredLabel.append(mastered,document.createTextNode('Mastered 👑'));
        row.append(copy,masteredLabel);
        review.appendChild(row);
      }
      confirm.disabled = !review.querySelector('select option:checked:not([value=""])');
      review.addEventListener('change',() => {
        confirm.disabled = ![...review.querySelectorAll('select')].some((select) => select.value);
      },{ once:true });
    };

    file.addEventListener('change',() => {
      const chosen = file.files?.[0];
      if (!chosen) return;
      const reader = new FileReader();
      reader.onload = () => {
        imageData = String(reader.result || '');
        preview.querySelector('img').src = imageData;
        preview.hidden = false;
        status.textContent = 'Screenshot ready. Tap Analyze Screenshot.';
        review.replaceChildren();
        confirm.disabled = true;
      };
      reader.readAsDataURL(chosen);
    });

    analyze.addEventListener('click',async () => {
      if (!imageData) return status.textContent = 'Choose a screenshot first.';
      analyze.disabled = true;
      analyze.textContent = 'Analyzing…';
      status.textContent = 'Looking for Sprites…';
      try {
        const config = window.SPRITE_CLOUD_CONFIG || {};
        if (!config.supabaseUrl || !config.supabaseAnonKey) throw new Error('vision-unavailable');
        const entries = catalog();
        const session = window.SPRITE_ACCOUNT_BRIDGE?.session?.();
        const bearer = session?.access_token || session?.accessToken || '';
        if (!bearer) throw new Error('sign-in-required');
        const response = await nativeFetch(`${String(config.supabaseUrl).replace(/\/$/,'')}/functions/v1/sprite-image-import`,{
          method:'POST',
          headers:{
            'Content-Type':'application/json',
            'apikey':config.supabaseAnonKey,
            'Authorization':`Bearer ${bearer}`
          },
          body:JSON.stringify({
            image:imageData,
            maxSprites:6,
            catalog:entries.map(({ familyId,variantId,familyName,variantName,rarity }) => ({ familyId,variantId,familyName,variantName,rarity }))
          })
        });
        if (!response.ok) throw new Error(`vision-${response.status}`);
        const result = await response.json();
        const matches = Array.isArray(result?.matches) ? result.matches.slice(0,6) : [];
        makeRows(matches);
        status.textContent = matches.length
          ? `Found ${matches.length} possible ${matches.length === 1 ? 'Sprite' : 'Sprites'}. Check every match before adding.`
          : 'No confident matches were found. You can choose the Sprites manually below.';
      } catch {
        makeRows([]);
        status.textContent = 'Automatic recognition is not connected on this DEV build yet. The review flow is ready, and you can choose a Sprite manually for testing.';
      } finally {
        analyze.disabled = false;
        analyze.textContent = 'Analyze Screenshot';
      }
    });

    dialog.querySelector('#v153ImportCancel').addEventListener('click',() => dialog.close());
    dialog.querySelector('#v153ImportForm').addEventListener('submit',async (event) => {
      event.preventDefault();
      const selected = [...review.querySelectorAll('select')].flatMap((select,index) => {
        if (!select.value) return [];
        const [familyId,variantId] = select.value.split('::');
        const entry = catalog().find((item) => item.familyId === familyId && item.variantId === variantId);
        if (!entry) return [];
        return [{ ...entry,mastered:Boolean(review.querySelector(`[data-mastered-index="${index}"]`)?.checked) }];
      });
      const unique = [...new Map(selected.map((item) => [`${item.familyId}:${item.variantId}`,item])).values()].slice(0,6);
      if (!unique.length) return;
      dialog.close();
      const originalHash = location.hash;
      for (const item of unique) {
        const tab = document.getElementById(`tab-${String(item.rarity).toLowerCase()}`);
        if (tab) {
          tab.click();
          await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
        }
        const card = document.querySelector(`.card[data-family-id="${CSS.escape(item.familyId)}"][data-variant-id="${CSS.escape(item.variantId)}"]`);
        if (!card) continue;
        const collect = card.querySelector('.collect-button');
        const crown = card.querySelector('.crown-button');
        if (collect?.getAttribute('aria-pressed') !== 'true') {
          collect?.click();
          await new Promise((resolve) => requestAnimationFrame(resolve));
        }
        if (item.mastered && crown?.getAttribute('aria-pressed') !== 'true') {
          crown?.click();
          await new Promise((resolve) => requestAnimationFrame(resolve));
        }
      }
      if (originalHash && location.hash !== originalHash) history.replaceState(null,'',originalHash);
      status.textContent = `${unique.length} ${unique.length === 1 ? 'Sprite' : 'Sprites'} added.`;
    });
  }

  function addImportLauncher() {
    if (document.getElementById('v153ImportLaunch')) return;
    const anchor = document.getElementById('variantCollapseToggle') || document.getElementById('trackerFilterBar');
    if (!anchor) return;
    const button = document.createElement('button');
    button.id = 'v153ImportLaunch';
    button.type = 'button';
    button.className = 'v153-import-launch';
    button.textContent = 'Import Screenshot';
    button.addEventListener('click',() => {
      ensureImporter();
      document.getElementById('v153ImportDialog').showModal();
    });
    anchor.insertAdjacentElement('afterend',button);
  }

  function enhance() {
    addImportLauncher();
    addRenameButtons();
    addPerFamilyCollapseButtons();
  }

  window.addEventListener('DOMContentLoaded',() => {
    ensureRenameDialog();
    ensureImporter();
    enhance();
    const observer = new MutationObserver(() => enhance());
    observer.observe(document.body,{ subtree:true,childList:true,attributes:true,attributeFilter:['class'] });
  },{ once:true });
})();
